#!/usr/bin/env python3
"""Reproducibly export offline cities and fixed IANA transitions for the browser.

Install scripts/requirements.txt, then run python scripts/export_data.py.
Runtime JavaScript needs neither Python nor an API. Historical transitions come
directly from TZif, including transitions separated by less than a day. Only the
TZif trailing POSIX recurrence is expanded by daily detection and second-level
bisection, through 2101, using this same packaged tzdata release.
"""

from __future__ import annotations

from datetime import datetime, timezone
import argparse
import hashlib
from importlib.resources import files
import json
from pathlib import Path
from zoneinfo import ZoneInfo
from zoneinfo._common import load_data

import geonamescache
import tzdata
import city_source


PROJECT = Path(__file__).resolve().parents[1]

START = int(datetime(1799, 1, 1, tzinfo=timezone.utc).timestamp())
END = int(datetime(2102, 1, 1, tzinfo=timezone.utc).timestamp())


def export_zone(name):
    resource = files("tzdata.zoneinfo").joinpath(*name.split("/"))
    with resource.open("rb") as stream:
        indices, transitions, offsets, _dst, _abbr, posix = load_data(stream)
    with resource.open("rb") as stream:
        zone = ZoneInfo.from_file(stream, key=name)

    def offset_at(stamp):
        return int(datetime.fromtimestamp(stamp, zone).utcoffset().total_seconds())

    initial = offset_at(START)
    result = [initial]
    current = initial
    for instant, index in zip(transitions, indices):
        if START < instant < END:
            following = offsets[index]
            if following != current:
                result.extend((instant, following))
                current = following
    # The slim TZif may leave post-2007 DST recurrence to its POSIX tail.
    # All earlier actual transitions were copied, rather than sampled.
    cursor = max(START, transitions[-1] if transitions else START)
    if posix and b"," in posix and cursor < END:
        current = offset_at(cursor)
        while cursor < END - 1:
            following = min(cursor + 86400, END - 1)
            after = offset_at(following)
            if after != current:
                low, high = cursor, following
                while high - low > 1:
                    middle = (low + high) // 2
                    if offset_at(middle) == current:
                        low = middle
                    else:
                        high = middle
                current = offset_at(high)
                result.extend((high, current))
                cursor = high
            else:
                cursor = following
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=PROJECT / "public" / "data",
                        help="Output directory (default: public/data).")
    parser.add_argument("--check", action="store_true",
                        help="Compare generated bytes with existing output without writing files.")
    args = parser.parse_args()
    if tzdata.__version__ != "2026.6":
        raise SystemExit(f"Expected fixed tzdata 2026.6, got {tzdata.__version__}")
    if geonamescache.__version__ != "3.0.2":
        raise SystemExit(f"Expected fixed geonamescache 3.0.2, got {geonamescache.__version__}")
    zone_names = sorted(name for name in files("tzdata").joinpath("zones").read_text().splitlines()
                        if name and name not in {"Factory", "localtime"})
    tables = []
    zone_indices = {}
    dedup = {}
    for name in zone_names:
        table = export_zone(name)
        key = tuple(table)
        if key not in dedup:
            dedup[key] = len(tables)
            tables.append(table)
        zone_indices[name] = dedup[key]
    timezones = {"format": 1, "version": tzdata.__version__, "iana": tzdata.IANA_VERSION,
                 "start": START, "end": END, "zones": zone_indices, "tables": tables}

    records = city_source.load_city_records()
    rows = []
    for identity, record in sorted(records.items()):
        data = record.data
        if data["timezone"] not in zone_indices:
            raise ValueError(f"City {identity}: timezone is absent from the fixed database")
        rows.append([data["id"], data["name"], data["country"], data["admin"],
                     data["latitude"], data["longitude"], data["timezone"], data["label"],
                     record.primary, record.population, list(record.aliases)])
    city_data = {
        "format": 1,
        "version": f"geonamescache {geonamescache.__version__}",
        "source": "GeoNames, via geonamescache (CC BY 4.0)",
        "timezoneVersion": tzdata.__version__,
        "common": [str(identity) for identity in city_source.COMMON_CITY_IDS],
        "timezones": zone_names,
        "columns": ["id", "name", "country", "admin", "latitude", "longitude", "timezone",
                    "label", "primary", "population", "aliases"],
        "places": rows,
    }
    output = args.output_dir
    if not args.check:
        output.mkdir(parents=True, exist_ok=True)
    mismatches = []
    for filename, value in [("timezones.json", timezones), ("places.json", city_data)]:
        target = output / filename
        content = json.dumps(value, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        digest = hashlib.sha256(content).hexdigest()
        if args.check:
            if target.is_file() and target.read_bytes() == content:
                print(f"{filename}: identical ({len(content):,} bytes; SHA-256 {digest})")
            else:
                mismatches.append(filename)
                print(f"{filename}: differs or missing")
        else:
            target.write_bytes(content)
            print(f"{filename}: {len(content):,} bytes; SHA-256 {digest}")
    print(f"Cities: {len(rows):,}; zones: {len(zone_names)}; unique tables: {len(tables)}")
    if mismatches:
        raise SystemExit("Data verification failed: " + ", ".join(mismatches))


if __name__ == "__main__":
    main()
